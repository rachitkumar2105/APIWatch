// Builds the static site into dist/ for Vercel (or any static host).
// - Writes dist/config.js from APIWATCH_API_URL, so the backend URL is set in the
//   host's environment settings, not in code.
// - Narrows each page's Content-Security-Policy connect-src to that exact origin.
// - Stamps asset URLs with a build id so browsers fetch fresh files after a deploy.
// No dependencies: plain Node 18+.

import { cp, mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "dist");
const onVercel = Boolean(process.env.VERCEL);

function fail(message) {
  console.error(`\nBuild failed: ${message}\n`);
  process.exit(1);
}

const raw = (process.env.APIWATCH_API_URL || "").trim();
if (!raw && onVercel) {
  fail(
    "APIWATCH_API_URL is not set. In Vercel: Project Settings > Environment Variables, " +
      "add APIWATCH_API_URL = https://<your-space>.hf.space and redeploy."
  );
}

let apiUrl;
try {
  apiUrl = new URL(raw || "http://localhost:8000");
} catch {
  fail(`APIWATCH_API_URL is not a valid URL: "${raw}"`);
}
const isLocal = ["localhost", "127.0.0.1"].includes(apiUrl.hostname);
if (apiUrl.protocol !== "https:" && !isLocal) {
  fail(`APIWATCH_API_URL must use https (got ${apiUrl.protocol}//${apiUrl.host}).`);
}
const apiOrigin = apiUrl.origin;
const apiBase = `${apiOrigin}${apiUrl.pathname}`.replace(/\/+$/, "");
const buildId = (process.env.VERCEL_GIT_COMMIT_SHA || Date.now().toString(36)).slice(0, 10);

await rm(out, { recursive: true, force: true });
await mkdir(out, { recursive: true });

const copy = ["assets", "favicon.svg"];
for (const entry of copy) {
  await cp(join(root, entry), join(out, entry), { recursive: true });
}

const pages = (await readdir(root)).filter((name) => name.endsWith(".html"));
for (const page of pages) {
  let html = await readFile(join(root, page), "utf8");
  html = html
    .replace("connect-src 'self' http://localhost:8000 http://127.0.0.1:8000", `connect-src 'self' ${apiOrigin}`)
    .replaceAll("?v=dev", `?v=${buildId}`);
  await writeFile(join(out, page), html);
}

await writeFile(
  join(out, "config.js"),
  `// Generated by scripts/build.mjs. Do not edit.\nwindow.APIWATCH_CONFIG = Object.freeze({ apiUrl: ${JSON.stringify(apiBase)} });\n`
);

console.log(`Built ${pages.length} pages into dist/ (API: ${apiBase}, build ${buildId}).`);
